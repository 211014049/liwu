def slugify(text):
    """生成URL友好的slug"""
    return hashlib.md5(text.encode('utf-8')).hexdigest()[:10]

def get_articles_by_category(cat_slug):
    """获取分类下的文章"""
    return [a for a in ARTICLES if a["cat"] == cat_slug]

def get_related_articles(article, limit=5):
    """获取相关文章（同分类）"""
    same_cat = [a for a in ARTICLES if a["cat"] == article["cat"] and a["title"] != article["title"]]
    return same_cat[:limit]

def get_cat_info(slug):
    """获取分类信息"""
    for c in CATEGORIES:
        if c["slug"] == slug:
            return c
    return None

