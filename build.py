def generate_sitemap():
    urls = []
    # 首页
    urls.append(f"{SITE_URL}/")
    # 分类页
    for cat in CATEGORIES:
        if len(get_articles_by_category(cat["slug"])) > 0:
            urls.append(f"{SITE_URL}/category/{cat['slug']}.html")
    # 文章页
    for a in ARTICLES:
        urls.append(f"{SITE_URL}/gift/{slugify(a['title'])}.html")
    # 政策页
    urls.append(f"{SITE_URL}/about.html")
    urls.append(f"{SITE_URL}/privacy-policy.html")
    urls.append(f"{SITE_URL}/contact.html")
    
    sitemap = f"""<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
"""
    for url in urls:
        sitemap += f"  <url>\n    <loc>{url}</loc>\n    <lastmod>{datetime.now().strftime('%Y-%m-%d')}</lastmod>\n    <changefreq>weekly</changefreq>\n    <priority>0.8</priority>\n  </url>\n"
    sitemap += "</urlset>"
    
    with open(os.path.join(DOCS_DIR, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write(sitemap)
    print(f"✓ Sitemap: {len(urls)} URLs")

